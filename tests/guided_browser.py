"""Three-step workflow; isolated DEMO storage and synthetic places, never production."""
from playwright.sync_api import sync_playwright, expect
import json,os,shutil
BASE=os.environ.get('INDRAYA_WEB_URL','http://127.0.0.1:8095')
OUT=os.environ.get('INDRAYA_SCREENSHOTS','/workspace/outputs/indraya-flow');os.makedirs(OUT,exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=shutil.which('chromium'),headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':390,'height':844});errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
 page.route('https://photon.komoot.io/**',lambda r:r.fulfill(json={'features':[{'type':'Feature','geometry':{'type':'Point','coordinates':[-149.106,61.584]},'properties':{'name':'TEST Palmer place','city':'Palmer','state':'Alaska','country':'United States','osm_type':'N','osm_id':123}}]}))
 def btn(name):return page.get_by_role('button',name=name,exact=True).or_(page.get_by_role('radio',name=name,exact=True)).or_(page.get_by_role('checkbox',name=name,exact=True))
 def click(name):print('ACTION',name,flush=True);btn(name).click()
 def place():
  page.get_by_label('Search observation location',exact=True).fill('Palmer fixture');click('Search');click('TEST Palmer place')
 def pick(group,query,leaf):
  click(group);page.get_by_label('Find an observation type',exact=True).fill(query);click(leaf+' · '+group)
 def consent():page.get_by_role('checkbox',name='I checked this attachment for sensitive details').check()
 def records():return json.loads(page.evaluate("localStorage.getItem('indraya.demo.observations.v1')"))
 page.goto(BASE,wait_until='networkidle',timeout=90000);click('Share an observation')
 expect(page.get_by_text('DEMO · Nothing is shared publicly',exact=True)).to_be_visible()
 expect(page.get_by_role('heading',name='What did you notice?',exact=True)).to_be_visible();expect(btn('Continue')).to_be_disabled()
 click('Travel & Transportation');click('Narrow it down: Road conditions');click('What best fits?: Black ice')
 expect(page.get_by_role('dialog')).to_have_count(0)
 click('Add a note · Optional');page.get_by_label('Description',exact=True).fill('Synthetic observation for a three-step test.')
 click('Edit title');page.get_by_label('Title',exact=True).fill('TEST custom black ice title')
 click('Add details · Optional');click('Visibility: Reduced')
 click('＋ Add a related observation');page.get_by_label('Find related observations').fill('strong wind');click('Add Strong wind observed')
 expect(btn('Remove Strong wind observed')).to_be_checked();click('Remove Strong wind observed')
 page.get_by_label('Find an observation type',exact=True).fill('whiteout');click('Whiteout · Travel & Transportation')
 expect(page.get_by_label('Title',exact=True)).to_have_value('TEST custom black ice title')
 expect(btn('Visibility: Reduced')).to_be_checked()
 page.screenshot(path=OUT+'/step-1.png',full_page=True)
 click('Continue');expect(page.get_by_role('heading',name='When and where?',exact=True)).to_be_visible()
 expect(btn('Change category or observation')).to_have_count(0)
 click('Review observation');expect(page.get_by_role('alert')).to_contain_text('Choose where')
 place();click('Earlier today');click('Use observation time')
 with page.expect_file_chooser() as fc:click('Choose photo')
 fc.value.set_files('tests/fixtures/photo-with-metadata.jpg')
 expect(page.get_by_label('Selected attachment preview')).to_be_visible(timeout=15000);expect(btn('Review observation')).to_be_disabled();consent()
 click('Back');expect(page.get_by_label('Title',exact=True)).to_have_value('TEST custom black ice title')
 click('Continue');expect(page.get_by_text('Selected: TEST Palmer place',exact=True)).to_be_visible()
 expect(page.get_by_label('Selected attachment preview')).to_be_visible();click('Review observation')
 expect(page.get_by_role('heading',name='Review and share',exact=True)).to_be_visible()
 click('Edit observation');expect(page.get_by_label('Description',exact=True)).to_have_value('Synthetic observation for a three-step test.')
 click('Continue');click('Review observation');page.screenshot(path=OUT+'/step-3.png',full_page=True)
 click('Share observation');expect(page.get_by_role('heading',name='Saved on this device',exact=True)).to_be_visible()
 r=records();assert len(r)==1 and r[0]['event_type_id']=='whiteout' and r[0]['answers']['visibility']=='reduced'
 assert r[0]['latitude']==61.58 and r[0]['longitude']==-149.11 and r[0]['photo_uri'].startswith('data:image/jpeg')
 click('Return to map');click('Share an observation');pick('Travel & Transportation','black ice','Black ice')
 click('Add a note · Optional');page.get_by_label('Description',exact=True).fill('Synthetic video observation, no production data.');click('Continue');place()
 with page.expect_file_chooser() as fc:click('Choose video')
 fc.value.set_files('tests/fixtures/video-with-metadata.mp4')
 expect(page.locator('video')).to_have_count(1,timeout=15000)
 page.wait_for_function('document.querySelector("video").readyState >= 2')
 page.locator('video').evaluate('(v)=>v.play()');page.wait_for_function('document.querySelector("video").currentTime > 0.1');page.locator('video').evaluate('(v)=>v.pause()')
 expect(btn('Review observation')).to_be_disabled();consent()
 click('Review observation');click('Share observation');expect(page.get_by_role('heading',name='Saved on this device',exact=True)).to_be_visible()
 assert records()[-1]['media_kind']=='video' and records()[-1]['photo_uri'].startswith('data:video/mp4')
 click('Return to map');click('Share an observation');pick('Wildlife & Animals','encounter','Wildlife encounter')
 click('Add a note · Optional');page.get_by_label('Description',exact=True).fill('Synthetic sensitive encounter for private review.')
 click('Add details · Optional');click('What animal?: Other animal');page.get_by_label('Other animal',exact=True).fill('Synthetic private text')
 click('What animal?: Moose');expect(page.get_by_label('Other animal',exact=True)).to_have_count(0)
 click('What did you observe?: Attack reported');click('Continue');place();click('Review observation');click('Send for private review')
 expect(page.get_by_role('heading',name='Saved for private review',exact=True)).to_be_visible()
 r=records()[-1];assert r['status']=='review' and r['privacy_class']=='restricted' and 'other_animal' not in r['answers'] and r['place_name']=='Regional information'
 click('View my observations');expect(page.get_by_text('Moose encounter · attack reported',exact=False)).to_be_visible()
 for width,height in [(320,568),(390,844),(768,1024)]:
  page.goto(BASE+'/report',wait_until='networkidle');page.set_viewport_size({'width':width,'height':height})
  box=btn('Continue').bounding_box();assert box and box['y']>=0 and box['y']+box['height']<=height
  assert page.evaluate('document.documentElement.scrollWidth')<=width
  page.screenshot(path=f'{OUT}/start-{width}.png',full_page=True)
 assert not errors,errors
 print('PASS: inline choices, three steps, chips, edit/back preservation, location/consent, photo/video demo save, private holds, pruning, responsive footer; no console errors')
 b.close()
